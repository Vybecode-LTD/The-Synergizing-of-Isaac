# ---------------------------------------------------------------- helpers


def read_json(path: Path):
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(value, ensure_ascii=False, indent=1) + "\n"
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def slugify(name: str) -> str:
    """URL slug for a game name: "Mom's Knife" -> "moms-knife", "???'s Only Friend" -> "blue-babys-only-friend"."""
    s = name.replace("???", "blue baby").replace("<3", "less than three")
    s = s.replace("'", "").replace("’", "").replace("&", " and ")
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return s


def norm(name: str) -> str:
    """Loose key for matching names typed by people: case, punctuation and '&' are ignored."""
    return re.sub(r"[^a-z0-9]", "", name.lower().replace("&", "and"))


def png_size(path: Path) -> tuple[int, int]:
    with path.open("rb") as f:
        head = f.read(26)
    if head[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"not a PNG: {path}")
    return struct.unpack(">II", head[16:24])


def number(value: str) -> float | int:
    n = float(value)
    return int(n) if n == int(n) else n


# Text that was saved as UTF-8, read as Windows-1252 and saved again shows up as runs like "A-tilde, cent".
# Built with chr() so this file stays plain ASCII: lead bytes C3/C2/E2, then a continuation-range character.
MOJIBAKE = re.compile(
    "[" + chr(0xC3) + chr(0xC2) + chr(0xE2) + "]"
    "[" + chr(0x80) + "-" + chr(0xBF) + chr(0x20AC) + chr(0x201A) + "-" + chr(0x203A) + "]"
)


def demojibake(text: str) -> str:
    """Undo UTF-8 read as Windows-1252, as many times as it was done (the old synergy file did it twice)."""
    for _ in range(3):
        if not MOJIBAKE.search(text):
            break
        raw = bytearray()
        try:
            for ch in text:
                raw += bytes([ord(ch)]) if ord(ch) < 256 else ch.encode("cp1252")
            text = raw.decode("utf-8")
        except (UnicodeEncodeError, UnicodeDecodeError):
            break
    return text


def sentence(text: str) -> str:
    text = (text or "").strip()
    return text[:1].upper() + text[1:] if text else ""


# ---------------------------------------------------------------- import-sources


def import_sources(tracker: Path, facts: Path) -> None:
    """Copy the files we use out of a tracker clone and the extracted game facts. Nothing is executed."""
    SOURCES.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(tracker / "items.json", SOURCES / "tracker-items.json")
    shutil.copyfile(tracker / "LICENSE.txt", SOURCES / "TRACKER-LICENSE.txt")

    merged = {}
    for name in ("quality", "players", "pools"):
        part = read_json(facts / f"{name}.json")
        merged[name] = part
    write_json(SOURCES / "game-facts.json", merged)

    roster = read_json(SOURCES / "tracker-items.json")
    src = tracker / "collectibles"
    copied = 0
    for key in roster:
        if not key.isdigit():
            continue
        n = int(key)
        if 0 < n < 1000:
            dest = SPRITES / "items" / f"{n:03d}.png"
        elif 2000 < n < 3000:
            dest = SPRITES / "trinkets" / f"{n - 2000:03d}.png"
        else:
            continue
        sprite = src / f"collectibles_{n:03d}.png"
        if not sprite.exists():
            continue
        if png_size(sprite) != (64, 64):
            raise SystemExit(f"unexpected sprite size: {sprite}")
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(sprite, dest)
        copied += 1

    chars = LEGACY / "Images" / "Characters"
    for _, slug, _, _, legacy_file in CHARACTERS:
        dest = SPRITES / "characters" / f"{slug}.png"
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(chars / legacy_file, dest)
    print(f"imported: tracker-items.json, game-facts.json, {copied} sprites, {len(CHARACTERS)} character sprites")


# ---------------------------------------------------------------- build


def transformation_tags(sets: list[dict]) -> dict[tuple[str, str], dict[int, list[str]]]:
    """(kind, record key) -> id -> the transformations it counts toward, from data/transformations.json."""
    tags: dict[tuple[str, str], dict[int, list[str]]] = {}
    for kind, fields in TRANSFORMATION_FIELDS.items():
        for field, key in fields:
            by_id = tags.setdefault((kind, key), {})
            for t in sets:
                members = t.get(field)
                if not isinstance(members, list):
                    # The same words validate uses: build stops here rather than guessing an empty list.
                    raise ValueError(f"transformation {t.get('id', '?')!r}: {field} must be a list, empty if none")
                for n in members:
                    by_id.setdefault(n, []).append(t["id"])
    return {k: {n: sorted(ids) for n, ids in v.items()} for k, v in tags.items()}


def build_record(n: int, raw: dict, facts: dict | None, pools: list[str], kind: str, tags: dict) -> dict:
    rec: dict = {"id": n, "slug": "", "name": raw["name"].strip()}
    stats = {ours: number(raw[theirs]) for theirs, ours in STATS.items() if raw.get(theirs) not in (None, "")}
    rec["dlc"] = raw.get("introduced_in") or "Unknown"
    rec["effect"] = sentence(raw.get("text", ""))
    if facts and "quality" in facts:
        rec["quality"] = facts["quality"]
    if stats:
        rec["stats"] = stats
    for _, key in TRANSFORMATION_FIELDS[kind]:
        if n in tags[(kind, key)]:
            rec[key] = tags[(kind, key)][n]
    if pools:
        rec["pools"] = pools
    return rec


def assign_slugs(records: list[dict], overrides: dict[int, str]) -> None:
    seen: dict[str, int] = {}
    for rec in records:
        slug = overrides.get(rec["id"]) or slugify(rec["name"])
        if not slug:
            raise SystemExit(f"no slug for {rec['id']} {rec['name']!r}: add an override")
        if slug in seen:
            raise SystemExit(f"slug {slug!r} used by {seen[slug]} and {rec['id']}: add an override")
        seen[slug] = rec["id"]
        rec["slug"] = slug


def build() -> None:
    roster = read_json(SOURCES / "tracker-items.json")
    facts = read_json(SOURCES / "game-facts.json")
    quality = facts["quality"]
    pools_by_id = facts["pools"]["pools"]
    tags = transformation_tags(read_json(DATA / "transformations.json")["transformations"])

    items: list[dict] = []
    trinkets: list[dict] = []
    for key in sorted((k for k in roster if k.isdigit()), key=int):
        n = int(key)
        raw = roster[key]
        if 0 < n < 1000:
            if n in ITEM_HIDDEN or not raw.get("shown", True):
                continue
            pools = [p for p in pools_by_id.get(key, []) if not p.startswith(SKIP_POOL_PREFIX)]
            rec = build_record(n, raw, quality["items"].get(key), sorted(set(pools)), "item", tags)
            rec["name"] = ITEM_NAME_OVERRIDES.get(n, rec["name"])
            rec["type"] = "active" if raw.get("space") else "passive"
            items.append(rec)
        elif 2000 < n < 3000:
            if not raw.get("shown", True):
                continue
            trinkets.append(build_record(n - 2000, raw, None, [], "trinket", tags))

    assign_slugs(items, ITEM_SLUG_OVERRIDES)
    assign_slugs(trinkets, {})

    item_ids = {i["id"] for i in items}
    players = facts["players"]["players"]
    characters = []
    for game_id, slug, name, game_name, _ in CHARACTERS:
        p = players[str(game_id)]
        start = [i for i in p["items"] if i in item_ids]
        if game_id == 19:  # Jacob and Esau are two entries in the game's table
            start += [i for i in players["20"]["items"] if i in item_ids]
        rec = {"slug": slug, "name": name, "tainted": slug.startswith("tainted-"), "gameId": game_id}
        if game_name:
            rec["gameName"] = game_name
        if start:
            rec["startingItems"] = start
        if p["pocketActive"] in item_ids:
            rec["pocketActive"] = p["pocketActive"]
        characters.append(rec)

    write_json(DATA / "items.json", items)
    write_json(DATA / "trinkets.json", trinkets)
    write_json(DATA / "characters.json", characters)
    write_meta()
    print(f"built: {len(items)} items, {len(trinkets)} trinkets, {len(characters)} characters")


def write_meta() -> None:
    """Stamp the data with the day it was last built, for "last updated" lines and the sitemap."""
    import datetime

    write_json(
        DATA / "meta.json",
        {"updated": datetime.date.today().isoformat(), "gameVersion": "Repentance 1.7.9b"},
    )


# ---------------------------------------------------------------- migrate-synergies


def synergy_id(entry: dict, item_slug: dict, trinket_slug: dict, char_slug: dict) -> str:
    parts = sorted(item_slug[norm(n)] for n in entry["items"])
    parts += sorted("t-" + trinket_slug[norm(n)] for n in entry["trinkets"])
    parts += sorted("c-" + char_slug[norm(n)] for n in entry["characters"])
    return "+".join(parts)


def migrate_synergies() -> None:
    """One-off: bring the desktop app's synergy list across, using the game's real names."""
    legacy = read_json(LEGACY / "Data" / "synergies.json")
    items = {norm(i["name"]): i for i in read_json(DATA / "items.json")}
    trinkets = {norm(t["name"]): t for t in read_json(DATA / "trinkets.json")}
    chars = {norm(c["name"]): c for c in read_json(DATA / "characters.json")}

    out, problems, used = [], [], {}
    for entry in legacy:
        fixed = {"id": "", "items": [], "trinkets": [], "characters": []}
        for name in entry.get("items", []):
            key = LEGACY_ITEM_ALIASES.get(norm(name), norm(name))
            if key in items:
                fixed["items"].append(items[key]["name"])
            else:
                problems.append(f"item {name!r}")
        for name in entry.get("trinkets", []):
            if norm(name) in trinkets:
                fixed["trinkets"].append(trinkets[norm(name)]["name"])
            else:
                problems.append(f"trinket {name!r}")
        for name in entry.get("characters", []):
            if norm(name) in chars:
                fixed["characters"].append(chars[norm(name)]["name"])
            else:
                problems.append(f"character {name!r}")
        fixed["rating"] = entry["rating"]
        fixed["description"] = demojibake(entry["description"]).strip()
        base = synergy_id(
            fixed,
            {k: v["slug"] for k, v in items.items()},
            {k: v["slug"] for k, v in trinkets.items()},
            {k: v["slug"] for k, v in chars.items()},
        )
        used[base] = used.get(base, 0) + 1
        fixed["id"] = base if used[base] == 1 else f"{base}~{used[base]}"
        out.append(fixed)
    if problems:
        raise SystemExit("unresolved legacy names: " + ", ".join(sorted(set(problems))))
    write_json(DATA / "synergies.json", out)
    write_meta()
    print(f"migrated: {len(out)} synergies")


