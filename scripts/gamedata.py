def validate(data_dir: Path = DATA) -> list[str]:
    """Return every problem found in the data folder. An empty list means it is consistent."""
    problems: list[str] = []
    items = read_json(data_dir / "items.json")
    trinkets = read_json(data_dir / "trinkets.json")
    characters = read_json(data_dir / "characters.json")
    synergies = read_json(data_dir / "synergies.json")

    for label, records, key in (("item", items, "id"), ("trinket", trinkets, "id"), ("character", characters, "slug")):
        for field in (key, "slug", "name"):
            values = [r.get(field) for r in records]
            dupes = sorted({str(v) for v in values if values.count(v) > 1})
            if dupes:
                problems.append(f"{label}: duplicate {field}: {', '.join(dupes)}")
        for r in records:
            if not r.get("slug") or not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", r["slug"]):
                problems.append(f"{label} {r.get('name')!r}: bad slug {r.get('slug')!r}")

    for r in items:
        if r.get("quality") not in (0, 1, 2, 3, 4):
            problems.append(f"item {r['name']!r}: quality missing or out of range")
        if r.get("type") not in ("active", "passive"):
            problems.append(f"item {r['name']!r}: bad type")

    sprite_dir = data_dir / "sprites"
    for folder, records, stem in (
        ("items", items, lambda r: f"{r['id']:03d}"),
        ("trinkets", trinkets, lambda r: f"{r['id']:03d}"),
        ("characters", characters, lambda r: r["slug"]),
    ):
        for r in records:
            if not (sprite_dir / folder / f"{stem(r)}.png").exists():
                problems.append(f"{folder}: no sprite for {r['name']!r}")

    item_names = {i["name"] for i in items}
    item_ids = {i["id"] for i in items}
    trinket_names = {t["name"] for t in trinkets}
    char_names = {c["name"] for c in characters}
    for c in characters:
        for i in c.get("startingItems", []) + ([c["pocketActive"]] if c.get("pocketActive") else []):
            if i not in item_ids:
                problems.append(f"character {c['name']!r}: unknown starting item {i}")

    seen_ids: set[str] = set()
    seen_keys: dict[tuple, str] = {}
    for n, s in enumerate(synergies):
        where = f"synergy #{n} ({s.get('id', '?')})"
        if not s.get("id") or s["id"] in seen_ids:
            problems.append(f"{where}: missing or duplicate id")
        seen_ids.add(s.get("id", ""))
        if s.get("rating") not in RATINGS:
            problems.append(f"{where}: rating {s.get('rating')!r} is not one of {'/'.join(RATINGS)}")
        if not (s.get("description") or "").strip():
            problems.append(f"{where}: empty description")
        if MOJIBAKE.search(s.get("description") or ""):
            problems.append(f"{where}: description has garbled characters (wrong text encoding)")
        if not s.get("items") and not s.get("trinkets"):
            problems.append(f"{where}: needs at least one item or trinket")
        for field, known in (("items", item_names), ("trinkets", trinket_names), ("characters", char_names)):
            values = s.get(field, [])
            if len(set(values)) != len(values):
                problems.append(f"{where}: repeated name in {field}")
            for name in values:
                if name not in known:
                    problems.append(f"{where}: unknown {field[:-1]} {name!r}")
        key = (tuple(sorted(s.get("items", []))), tuple(sorted(s.get("trinkets", []))), tuple(sorted(s.get("characters", []))))
        if key in seen_keys:
            problems.append(f"{where}: same combination as {seen_keys[key]}")
        seen_keys[key] = s.get("id", "?")

    problems += validate_transformations(read_json(data_dir / "transformations.json"), items, trinkets)
    return problems


def validate_transformations(doc: dict, items: list[dict], trinkets: list[dict]) -> list[str]:
    """data/transformations.json is well formed, names real pickups, and the built tags agree with it."""
    problems: list[str] = []
    sets = doc.get("transformations", [])
    known = {"item": {i["id"] for i in items}, "trinket": {t["id"] for t in trinkets}}
    any_malformed = False
    for field in ("id", "name"):
        values = [t.get(field) for t in sets]
        dupes = sorted({str(v) for v in values if values.count(v) > 1})
        if dupes:
            problems.append(f"transformations: duplicate {field}: {', '.join(dupes)}")
    for t in sets:
        where = f"transformation {t.get('id', '?')!r}"
        # type() is int, not isinstance: a JSON true is an int to Python and would pass.
        if type(t.get("needs")) is not int or t["needs"] < 1:
            problems.append(f"{where}: needs must be a whole number above 0")
        if not t.get("page") or type(t.get("revision")) is not int:
            problems.append(f"{where}: no wiki page and revision to source it")
        # The browser reads all four lists with no default: a missing one crashes the build summary.
        fields = [f for pairs in TRANSFORMATION_FIELDS.values() for f, _ in pairs]
        malformed = [f for f in fields if not isinstance(t.get(f), list)]
        for field in malformed:
            problems.append(f"{where}: {field} must be a list, empty if none")
        if malformed:
            any_malformed = True
            continue
        if not any(t.get(f) for fields in TRANSFORMATION_FIELDS.values() for f, _ in fields):
            problems.append(f"{where}: counts nothing")
        for kind, ((rep, _), (plus, _)) in TRANSFORMATION_FIELDS.items():
            both = set(t.get(rep, [])) & set(t.get(plus, []))
            if both:
                problems.append(f"{where}: {sorted(both)} in both {rep} and {plus}")
            for field in (rep, plus):
                values = t.get(field, [])
                if len(set(values)) != len(values):
                    problems.append(f"{where}: repeated id in {field}")
                for n in values:
                    if n not in known[kind]:
                        problems.append(f"{where}: unknown {kind} id {n} in {field}")

    if any_malformed:
        # Tags derived from a malformed file would be wrong; fix the lists first, then compare.
        return problems
    tags = transformation_tags(sets)
    for kind, records in (("item", items), ("trinket", trinkets)):
        for r in records:
            for _, key in TRANSFORMATION_FIELDS[kind]:
                if r.get(key, []) != tags[(kind, key)].get(r["id"], []):
                    problems.append(f"{kind} {r['name']!r}: {key} differs from transformations.json (run build)")
    return problems


# ---------------------------------------------------------------- cli


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    imp = sub.add_parser("import-sources")
    imp.add_argument("--tracker", type=Path, required=True)
    imp.add_argument("--facts", type=Path, required=True)
    sub.add_parser("build")
    sub.add_parser("migrate-synergies")
    sub.add_parser("validate")
    args = parser.parse_args(argv)

    if args.command == "import-sources":
        import_sources(args.tracker, args.facts)
    elif args.command == "build":
        build()
    elif args.command == "migrate-synergies":
        migrate_synergies()
    elif args.command == "validate":
        problems = validate()
        for p in problems:
            print("PROBLEM", p)
        print(f"validate: {len(problems)} problem(s)")
        return 1 if problems else 0
    return 0


